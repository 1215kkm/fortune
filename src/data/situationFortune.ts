export function getTodaySituationFortune(situationId: string): {
  situation: SituationFortune;
  fortune: SituationFortune['fortunes'][0];
} | null {
  const situation = situationFortunes.find(s => s.id === situationId);
  if (!situation) return null;

  // 날짜 기반으로 일관된 결과 제공
  const today = new Date();
  const dateNumber = today.getFullYear() * 10000 + (today.getMonth() + 1) * 100 + today.getDate();
  const index = (dateNumber + situationId.length) % situation.fortunes.length;

  return {
    situation,
    fortune: situation.fortunes[index],
  };
}

